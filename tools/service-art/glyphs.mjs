#!/usr/bin/env node
/**
 * Bake the Lucide glyphs the catalogue actually uses into the API.
 *
 * The API renders a tile on demand for any service created after a release.
 * It cannot read `node_modules/lucide-react` at runtime (that is a front-end
 * package, and the office server may be installed from a packed build with no
 * dev dependencies), so this script writes the node data for exactly the icons
 * in `seed-data.ts` — plus a small set of sensible extras for icons a manager
 * may pick from the panel — into a plain TypeScript module.
 *
 * Output: apps/api/src/modules/catalog/lucide-glyphs.ts
 * Usage:  node tools/service-art/glyphs.mjs [--check]
 *
 * `--check` fails (exit 1) when the committed file is stale, so CI notices when
 * a new service introduces an icon nobody baked.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const iconsDir = path.join(root, 'node_modules/lucide-react/dist/esm/icons');
const target = path.join(root, 'apps/api/src/modules/catalog/lucide-glyphs.ts');

/** Icons a manager is likely to choose in the panel, beyond the seeded set. */
const EXTRA_ICONS = [
  'file-text', 'layout-grid', 'folder', 'badge-check', 'briefcase', 'calendar',
  'check-circle', 'circle-help', 'clipboard-list', 'credit-card', 'file-check',
  'globe', 'graduation-cap', 'handshake', 'heart-pulse', 'home', 'id-card',
  'info', 'landmark', 'link', 'map-pin', 'message-circle', 'package', 'phone',
  'receipt', 'scale', 'settings', 'shield', 'shopping-bag', 'sparkles', 'star',
  'stethoscope', 'truck', 'umbrella', 'user', 'users', 'wallet', 'building-2',
  'car-front', 'hand-coins', 'stamp', 'file-signature', 'gavel',
];

function readSeededIcons() {
  const seed = fs.readFileSync(path.join(root, 'apps/api/src/modules/catalog/seed-data.ts'), 'utf8');
  const icons = new Set();
  for (const match of seed.matchAll(/icon:\s*'([^']+)'/g)) {
    icons.add(match[1]);
  }
  return icons;
}

function loadNodes(name, depth = 0) {
  if (depth > 4) return null;
  const candidates = [name, name.replace(/-icon$/, ''), name.replace(/-2$/, '')];
  const file = candidates.map((candidate) => path.join(iconsDir, `${candidate}.mjs`)).find((candidate) => fs.existsSync(candidate));
  if (!file) return null;
  let source = fs.readFileSync(file, 'utf8');
  const alias = /^export \{ default \} from '\.\/([^']+)\.mjs';$/m.exec(source);
  if (alias) {
    source = fs.readFileSync(path.join(iconsDir, `${alias[1]}.mjs`), 'utf8');
  }
  const start = source.indexOf('const __iconData = ');
  if (start < 0) return null;
  const literal = source.slice(start + 'const __iconData = '.length, source.indexOf('};', start) + 1);
  let data;
  try {
    data = new Function(`return (${literal})`)();
  } catch {
    return null;
  }
  if (Array.isArray(data.node)) {
    return data.node.map(([tag, attrs]) => [tag, attrs ?? {}]);
  }
  return loadNodes(data.name ?? '', depth + 1);
}

const wanted = new Set([...readSeededIcons(), ...EXTRA_ICONS, 'file-text']);
const table = {};
const missing = [];
for (const name of [...wanted].sort()) {
  const nodes = loadNodes(name);
  if (!nodes) {
    missing.push(name);
    continue;
  }
  // Rounded to 3 decimals: the source uses long floats that would triple the file.
  table[name] = nodes.map(([tag, attrs]) => [
    tag,
    Object.fromEntries(Object.entries(attrs)
      .filter(([key]) => key !== 'key')
      .map(([key, value]) => [key, typeof value === 'number' ? Math.round(value * 1000) / 1000 : value])),
  ]);
}

const body = `/**
 * GENERATED by tools/service-art/glyphs.mjs — do not edit by hand.
 *
 * The Lucide node data for every icon the catalogue uses. The on-demand
 * artwork renderer draws these so a service created from the admin panel
 * looks exactly like one that shipped in the APK.
 */
export type GlyphNode = [tag: string, attrs: Record<string, string | number>];

export const LUCIDE_GLYPHS: Record<string, GlyphNode[]> = ${JSON.stringify(table, null, 0)};

/** Nearest known glyph for a name we do not have, so nothing renders empty. */
export function glyphFor(name: string): GlyphNode[] {
  const clean = String(name ?? '').trim().toLowerCase();
  return LUCIDE_GLYPHS[clean]
    ?? LUCIDE_GLYPHS[clean.replace(/-icon$/, '')]
    ?? LUCIDE_GLYPHS[clean.replace(/-2$/, '')]
    ?? LUCIDE_GLYPHS['file-text'];
}
`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== body) {
    console.error(`lucide-glyphs.ts is stale — run: node tools/service-art/glyphs.mjs`);
    process.exit(1);
  }
  console.log(`lucide-glyphs.ts is current (${Object.keys(table).length} icons)`);
  process.exit(0);
}

fs.writeFileSync(target, body);
console.log(`wrote ${path.relative(root, target)} — ${Object.keys(table).length} icons, ${(body.length / 1024).toFixed(1)} KB`);
if (missing.length) console.log(`not found in lucide: ${missing.join(', ')}`);
