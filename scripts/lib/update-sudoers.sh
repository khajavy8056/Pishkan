#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# The one privilege the admin panel needs, described in exactly one place.
#
# The "به‌روزرسانی" button in the panel runs `sudo pishkan update` without a
# password, which is root. That is only safe if the grant is narrow, so the
# narrow form is written here — once — and the checks in
# `tools/check_deploy.sh` assert its shape. Read it as three deliberate choices:
#
#  * **Enumerated arguments, not wildcards.** sudoers matches whole argument
#    lists, so only `check-update --json` and `update --json` are allowed. The
#    panel therefore cannot pass `--no-backup` (backups stay mandatory) and
#    cannot pass `--ref` (a compromised web process cannot repoint the server at
#    an arbitrary commit; choosing a specific release stays a human act done on
#    the machine, where `pishkan update --ref <SHA>` still works).
#  * **Nothing else is granted** — not `restart`, not `backup`, not a shell.
#    Everything else the panel does today stays inside the app.
#  * **`NOPASSWD` only for these two**, so the office never types a root
#    password into a browser.
#
# `visudo -c` runs on the *file we generated* before it is put in place: a broken
# sudoers file locks everybody out of the machine, and an updater must not be the
# thing that does it.
# ---------------------------------------------------------------------------

UPDATE_SUDOERS_PATH="/etc/sudoers.d/pishkan-update"

# The service user, if unspecified. Kept as an argument so `install.sh` (which
# knows it) and a hand-run on an odd install both get the same file.
update_sudoers_content() {
  local user="${1:-pishkan}" bin="${2:-/usr/local/bin/pishkan}"
  cat <<EOF
# Pishkan — the exact privilege the admin panel's update button needs.
# Generated by scripts/lib/update-sudoers.sh. Do not widen this line, and do not
# edit it by hand: change the generator, then run \`sudo pishkan provision\`.
${user} ALL=(root) NOPASSWD: ${bin} check-update --json, ${bin} update --json
EOF
}

# Install (or refresh) the grant. Idempotent: an identical file is left alone, so
# `provision` can be run on every update without churning /etc.
install_update_sudoers() {
  local user="${1:-pishkan}" bin="${2:-/usr/local/bin/pishkan}" tmp current
  command -v visudo >/dev/null 2>&1 || { warn "visudo نصب نیست؛ مجوز به‌روزرسانی از پنل اضافه نشد."; return 1; }
  [ -f "$bin" ] || { warn "مسیر ${bin} وجود ندارد؛ مجوز اضافه نشد (نصب کامل نشده است؟)."; return 1; }

  tmp="$(mktemp)"
  update_sudoers_content "$user" "$bin" >"$tmp"
  if ! visudo -cf "$tmp" >/dev/null 2>&1; then
    rm -f "$tmp"
    err "فایل sudoers ساخته‌شده معتبر نیست؛ چیزی در /etc تغییر نکرد."
    return 1
  fi

  if [ -f "$UPDATE_SUDOERS_PATH" ]; then
    current="$(cat "$UPDATE_SUDOERS_PATH" 2>/dev/null || true)"
    if [ "$current" = "$(cat "$tmp")" ]; then
      rm -f "$tmp"
      return 0
    fi
  fi

  install -m 0440 -o root -g root "$tmp" "$UPDATE_SUDOERS_PATH"
  rm -f "$tmp"
  ok "مجوز به‌روزرسانی از پنل نصب شد (${UPDATE_SUDOERS_PATH})."
}

# Used by `pishkan doctor` and the deploy check: is the grant present and exact?
update_sudoers_state() {
  local user="${1:-pishkan}" bin="${2:-/usr/local/bin/pishkan}"
  if [ ! -f "$UPDATE_SUDOERS_PATH" ]; then printf 'missing'; return 0; fi
  if grep -qF "NOPASSWD: ${bin} check-update --json, ${bin} update --json" "$UPDATE_SUDOERS_PATH" 2>/dev/null \
    && ! grep -qE 'NOPASSWD:.*(ALL|bash|sh |rm |curl )' "$UPDATE_SUDOERS_PATH" 2>/dev/null; then
    printf 'exact'
    return 0
  fi
  # A broader grant than the generator would produce is reported loudly rather
  # than quietly accepted — it is the kind of "fix" that outlives its reason.
  printf 'wider'
}
