/**
 * Default catalogue shipped with the installer/seed command.
 *
 * IMPORTANT: fees, durations and documents below are SAMPLE values marked with
 * `needs_review`. The office must confirm them with the official organisation
 * before publishing. Nothing here claims to be an official tariff.
 */

export interface FormField {
  key: string;
  label: string;
  type: 'text' | 'tel' | 'number' | 'national_id' | 'date' | 'textarea' | 'select' | 'radio' | 'checkbox' | 'file' | 'money' | 'iban' | 'postal_code';
  required?: boolean;
  options?: string[];
  placeholder?: string;
  help?: string;
}

/**
 * What a workflow step means for capacity and queue maths:
 * - action: the assigned employee must actively work on the case
 * - waiting_customer: progression is blocked on documents/info from the customer
 * - waiting_organization: the case sits with an external organization
 * - followup: the employee must chase the result again (still active work)
 * - delivery: handing the result back to the customer
 */
export type WorkflowStepKind = 'action' | 'waiting_customer' | 'waiting_organization' | 'followup' | 'delivery';

export interface WorkflowStep {
  title: string;
  description?: string;
  role?: string;
  requiresDocument?: boolean;
  kind?: WorkflowStepKind;
}

